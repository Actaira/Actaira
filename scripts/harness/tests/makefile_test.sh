test_test_target_fails_on_red_go_test() {
  go_module "$T/m"
  printf 'package demo\n\nimport "testing"\n\nfunc TestRed(t *testing.T) { t.Fatal("rojo") }\n' > "$T/m/pkg/demo/demo_test.go"
